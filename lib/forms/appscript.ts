export interface AppsScriptConfig {
  title: string
  secret: string
  keys: string[]
  permissions: {
    read: boolean
    edit: boolean
    delete: boolean
  }
}

/**
 * Generates Google Apps Script code for the user to paste into their sheet.
 * Header-driven, secret-validated, lock-protected, formula-injection safe.
 */
export function generateAppsScript(config: AppsScriptConfig): string {
  const { title, secret, keys, permissions } = config
  const cleanTitle = title.replace(/"/g, '\\"')
  const now = new Date().toISOString()
  const keysJson = JSON.stringify(keys)

  // Build the action handlers conditionally based on permissions
  const listCase = permissions.read ? 'case "list": return list_(sh, head, req);' : ""
  const updateCase = permissions.edit ? 'case "update": return update_(sh, head, req);' : ""
  const deleteCase = permissions.delete ? 'case "delete": return delete_(sh, req);' : ""

  const listFunction = permissions.read
    ? `
function list_(sh, head, req) {
  var lastRow = sh.getLastRow();
  if (lastRow < 2) {
    return out_({ ok: true, total: 0, entries: [], offset: 0, limit: 25 });
  }
  var offset = Math.max(0, parseInt(req.offset, 10) || 0);
  var limit = Math.min(100, Math.max(1, parseInt(req.limit, 10) || 25));
  var numRows = lastRow - 1;
  var data = sh.getRange(2, 1, numRows, head.length).getValues();
  
  // Map row arrays to key-value objects
  var all = [];
  for (var r = 0; r < data.length; r++) {
    var row = data[r];
    var obj = {};
    for (var c = 0; c < head.length; c++) {
      var k = head[c];
      obj[k] = row[c] !== null && row[c] !== undefined ? String(row[c]) : "";
    }
    all.push(obj);
  }

  // Newest first
  all.reverse();
  var paged = all.slice(offset, offset + limit);
  return out_({ ok: true, total: all.length, entries: paged, offset: offset, limit: limit });
}`
    : ""

  const updateFunction = permissions.edit
    ? `
function update_(sh, head, req) {
  if (!req.id || !req.updates) return out_({ ok: false, error: "bad_request" });
  var idCol = head.indexOf("_id") + 1;
  var lastRow = sh.getLastRow();
  if (lastRow < 2) return out_({ ok: false, error: "not_found" });

  var idValues = sh.getRange(2, idCol, lastRow - 1, 1).getValues();
  var targetRow = -1;
  for (var r = 0; r < idValues.length; r++) {
    if (String(idValues[r][0]) === String(req.id)) {
      targetRow = r + 2;
      break;
    }
  }
  if (targetRow < 0) return out_({ ok: false, error: "not_found" });

  for (var key in req.updates) {
    if (CONFIG.KEYS.indexOf(key) >= 0) {
      var col = head.indexOf(key) + 1;
      if (col > 0) {
        var cell = sh.getRange(targetRow, col);
        cell.setNumberFormat("@");
        cell.setValue(safeVal_(req.updates[key]));
      }
    }
  }
  return out_({ ok: true, id: req.id });
}`
    : ""

  const deleteFunction = permissions.delete
    ? `
function delete_(sh, req) {
  if (!req.id) return out_({ ok: false, error: "bad_request" });
  var lastRow = sh.getLastRow();
  if (lastRow < 2) return out_({ ok: false, error: "not_found" });

  var head = headers_(sh);
  var idCol = head.indexOf("_id") + 1;
  var idValues = sh.getRange(2, idCol, lastRow - 1, 1).getValues();
  var targetRow = -1;
  for (var r = 0; r < idValues.length; r++) {
    if (String(idValues[r][0]) === String(req.id)) {
      targetRow = r + 2;
      break;
    }
  }
  if (targetRow < 0) return out_({ ok: false, error: "not_found" });

  sh.deleteRow(targetRow);
  return out_({ ok: true, id: req.id });
}`
    : ""

  return `// Generated by ul0.site for "${cleanTitle}" on ${now}. Do not share this script.
const CONFIG = {
  SECRET: "${secret}",
  SHEET: "Responses",
  KEYS: ${keysJson},
  CAN: { read: ${permissions.read}, edit: ${permissions.edit}, remove: ${permissions.delete} }
};

function doGet() {
  return out_({ ok: true, service: "ul0-forms" });
}

function doPost(e) {
  var req;
  try {
    req = JSON.parse(e.postData.contents);
  } catch (x) {
    return out_({ ok: false, error: "bad_json" });
  }

  if (!req || req.secret !== CONFIG.SECRET) {
    return out_({ ok: false, error: "unauthorized" });
  }

  var write = req.action === "append" || req.action === "update" || req.action === "delete";
  var lock = LockService.getScriptLock();

  try {
    if (write) {
      lock.waitLock(10000);
    }

    var ss = SpreadsheetApp.getActiveSpreadsheet();
    var sh = ss.getSheetByName(CONFIG.SHEET);
    if (!sh) {
      return out_({ ok: false, error: "sheet_missing" });
    }

    var head = headers_(sh);
    var need = ["_id", "_submitted_at"].concat(CONFIG.KEYS);
    var missing = need.filter(function(k) { return head.indexOf(k) < 0; });
    if (missing.length > 0) {
      return out_({ ok: false, error: "schema_mismatch", missing: missing });
    }

    switch (req.action) {
      case "ping":
        return out_({ ok: true });
      case "append":
        return append_(sh, head, req);
      ${listCase}
      ${updateCase}
      ${deleteCase}
      default:
        return out_({ ok: false, error: "unknown_action" });
    }
  } catch (err) {
    var msg = String(err);
    return out_({ ok: false, error: msg.indexOf("lock") >= 0 ? "busy" : "server_error" });
  } finally {
    try { lock.releaseLock(); } catch (x) {}
  }
}

function out_(obj) {
  return ContentService.createTextOutput(JSON.stringify(obj))
    .setMimeType(ContentService.MimeType.JSON);
}

function headers_(sh) {
  var lastCol = sh.getLastColumn();
  if (lastCol < 1) return [];
  return sh.getRange(1, 1, 1, lastCol).getValues()[0].map(function(v) {
    return String(v).trim();
  });
}

function safeVal_(val) {
  if (val === null || val === undefined) return "";
  var str = String(val);
  if (str.length > 5000) str = str.substring(0, 5000);
  // Anti-Formula Injection: values beginning with =, +, -, @ are stored textually
  if (/^[=+\\-@]/.test(str)) {
    return "'" + str;
  }
  return str;
}

function append_(sh, head, req) {
  var rowData = req.row || {};
  var id = String(rowData._id || "");
  if (!id) return out_({ ok: false, error: "missing_id" });

  var lastRow = sh.getLastRow();
  var idCol = head.indexOf("_id") + 1;

  // Idempotency: verify if _id already exists to prevent duplicate entries on network retries
  if (lastRow >= 2 && idCol > 0) {
    var existingIds = sh.getRange(2, idCol, lastRow - 1, 1).getValues();
    for (var i = 0; i < existingIds.length; i++) {
      if (String(existingIds[i][0]) === id) {
        return out_({ ok: true, deduplicated: true, id: id });
      }
    }
  }

  // Construct row in exact header order
  var rowValues = [];
  for (var c = 0; c < head.length; c++) {
    var key = head[c];
    var val = rowData[key];
    if (Array.isArray(val)) {
      val = val.join(", ");
    }
    rowValues.push(safeVal_(val));
  }

  var targetRow = lastRow + 1;
  var rowRange = sh.getRange(targetRow, 1, 1, head.length);
  // Set number format to plain text '@' before writing values to prevent formula execution
  rowRange.setNumberFormat("@");
  rowRange.setValues([rowValues]);

  return out_({ ok: true, id: id });
}
${listFunction}
${updateFunction}
${deleteFunction}

/**
 * HOW TO UPDATE THIS SCRIPT:
 * 1. Open your Google Sheet -> Extensions -> Apps Script.
 * 2. Paste the updated code and save.
 * 3. Click Deploy -> Manage deployments.
 * 4. Click the Edit icon (pencil) next to your Active Web App.
 * 5. In Version, select "New version" and click Deploy.
 *    (This preserves your existing Web App URL without breaking connection)
 */
`
}
